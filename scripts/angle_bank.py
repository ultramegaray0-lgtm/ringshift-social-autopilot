"""Render campaign/copy/angles.json into ready-to-post copy with a tagged demo link per platform and angle.

    python scripts/angle_bank.py            -> campaign/copy/READY_TO_POST.md + data/campaign/links.json

Every link is the project page tagged with utm_source=<platform>, utm_campaign=angles, utm_content=<angle id>
(scripts/tracking.py), so a visit can be traced to the exact angle once GA4 is on the itch page, and Buffer's
per-post click count already can be. data/campaign/links.json lists every tagged link the campaign uses, so the
report can map a tag back to its angle and asset.
"""
import json
from pathlib import Path

import post_rules
import tracking

BASE_DIR = Path(__file__).resolve().parent.parent
ANGLES_FILE = BASE_DIR / "campaign" / "copy" / "angles.json"
OUT_FILE = BASE_DIR / "campaign" / "copy" / "READY_TO_POST.md"
LINKS_FILE = BASE_DIR / "data" / "campaign" / "links.json"
PROJECT_FILE = BASE_DIR / "data" / "project.json"
BLUESKY_MAX = 300          # Bluesky counts the link text itself


def load(path=ANGLES_FILE):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def project_url(path=PROJECT_FILE):
    return json.loads(Path(path).read_text(encoding="utf-8"))["project_url"]


def link(base, platform, campaign, angle_id):
    return tracking.tagged(base, platform, campaign, angle_id)


def render_angle(angle, base, campaign):
    """{platform: final text} with the tagged link filled in."""
    return {
        "x": angle["x"].replace("{link}", link(base, "x", campaign, angle["id"])),
        "bluesky": angle["bluesky"].replace("{link}", link(base, "bluesky", campaign, angle["id"])),
        "youtube": link(base, "youtube", campaign, angle["id"]),
    }


def problems(angle, base, campaign, root=BASE_DIR):
    """Every reason this angle must not be posted as written."""
    out = []
    texts = render_angle(angle, base, campaign)
    for name, text in (("x", texts["x"]), ("bluesky", texts["bluesky"])):
        if "{link}" in text or tracking.base_url(base) not in text:
            out.append(f"{name}: missing the demo link")
        for url in post_rules.URL_RE.findall(text):
            if not tracking.is_project_link(url, base):
                out.append(f"{name}: link other than the demo page: {url}")
    out += [f"x: {p}" for p in post_rules.validate_post(texts["x"], allow_urls=True, project_url=base)]
    if len(texts["bluesky"]) > BLUESKY_MAX:
        out.append(f"bluesky: {len(texts['bluesky'])} characters (max {BLUESKY_MAX})")
    if len(angle.get("shorts_title", "")) > 100:
        out.append("shorts_title over YouTube's 100 characters")
    if not (Path(root) / angle["asset"]).is_file():
        out.append(f"asset not found: {angle['asset']}")
    return out


def render(data, base):
    campaign = data["campaign"]
    lines = ["# Ready to post: 16 angles, one link per platform and angle", "",
             "Generated by `scripts/angle_bank.py` from `campaign/copy/angles.json`. Every text passed the same post",
             "rules as the X autopilot. Post one angle per day per platform; never the same angle twice on one platform.",
             "Record each post's URL in `data/campaign/ledger.json` so the report can match it.", ""]
    links = []
    for angle in data["angles"]:
        texts = render_angle(angle, base, campaign)
        lines += [f"## {angle['id']} · {angle['name']}", "", f"*Why:* {angle['why']}  ", f"*Media:* `{angle['asset']}`", "",
                  "**X**", "", "```", texts["x"], "```", "", "**Bluesky**", "", "```", texts["bluesky"], "```", "",
                  f"**YouTube Short** title: `{angle['shorts_title']}`  ", f"description link: {texts['youtube']}", ""]
        for platform in ("x", "bluesky", "youtube"):
            links.append({"angle": angle["id"], "asset": angle["asset"], "source": platform,
                          "url": link(base, platform, campaign, angle["id"])})
    return "\n".join(lines) + "\n", links


def main():
    data = load()
    base = project_url()
    bad = {a["id"]: problems(a, base, data["campaign"]) for a in data["angles"]}
    bad = {k: v for k, v in bad.items() if v}
    if bad:
        for angle_id, reasons in bad.items():
            print(f"{angle_id}: " + "; ".join(reasons))
        return 1
    text, links = render(data, base)
    OUT_FILE.write_text(text, encoding="utf-8")
    LINKS_FILE.parent.mkdir(parents=True, exist_ok=True)
    LINKS_FILE.write_text(json.dumps({"_help": "Every tagged demo link the hand-written angles use. Written by scripts/angle_bank.py.",
                                      "links": links}, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_FILE.relative_to(BASE_DIR)} ({len(data['angles'])} angles) and {LINKS_FILE.relative_to(BASE_DIR)} ({len(links)} links)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
